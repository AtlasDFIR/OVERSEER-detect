#!/usr/bin/env python3
"""Generate an ATT&CK coverage matrix (Markdown) from detections + hunts.

Writes docs/COVERAGE.md so reviewers can see, at a glance, which tactics the
repo covers. Run in CI to keep the doc in sync.
"""
from __future__ import annotations
import re
import sys
from collections import defaultdict
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML required")

ROOT = Path(__file__).resolve().parent.parent

# Minimal technique -> (name, tactic) map for techniques used in this repo.
TECH = {
    "T1059": ("Command and Scripting Interpreter", "Execution"),
    "T1059.001": ("PowerShell", "Execution"),
    "T1059.004": ("Unix Shell", "Execution"),
    "T1027": ("Obfuscated Files or Information", "Defense Evasion"),
    "T1078": ("Valid Accounts", "Initial Access / Persistence"),
    "T1078.004": ("Cloud Accounts", "Persistence"),
    "T1556.006": ("Multi-Factor Authentication", "Credential Access"),
    "T1071": ("Application Layer Protocol", "Command and Control"),
    "T1071.001": ("Web Protocols", "Command and Control"),
    "T1106": ("Native API", "Execution"),
    "T1218": ("System Binary Proxy Execution", "Defense Evasion"),
    "T1021": ("Remote Services", "Lateral Movement"),
    "T1558.003": ("Kerberoasting", "Credential Access"),
    "T1053.005": ("Scheduled Task", "Persistence"),
    "T1048.003": ("Exfiltration Over Unencrypted Non-C2 Protocol", "Exfiltration"),
    "T1071.004": ("DNS", "Command and Control"),
    "T1621": ("MFA Request Generation", "Credential Access"),
}

def techniques_in(text: str) -> set[str]:
    return set(re.findall(r"T\d{4}(?:\.\d{3})?", text))

def main() -> int:
    cov: dict[str, list[str]] = defaultdict(list)
    for f in (ROOT / "detections").glob("*.yml"):
        doc = yaml.safe_load(f.read_text())
        for t in doc.get("mitre", []):
            cov[t].append(f"detection: {doc['title']}")
    for f in (ROOT / "hunts").glob("h*.md"):
        for t in techniques_in(f.read_text()):
            cov[t].append(f"hunt: {f.stem}")

    by_tactic: dict[str, list[str]] = defaultdict(list)
    for t in sorted(cov):
        name, tactic = TECH.get(t, ("(unknown)", "Uncategorized"))
        sources = ", ".join(sorted(set(cov[t])))
        by_tactic[tactic].append(f"| `{t}` | {name} | {sources} |")

    lines = ["# ATT&CK Coverage", "",
             "_Auto-generated by `scripts/coverage_report.py`. Do not edit by hand._", ""]
    for tactic in sorted(by_tactic):
        lines += [f"## {tactic}", "",
                  "| Technique | Name | Covered by |",
                  "|-----------|------|------------|",
                  *by_tactic[tactic], ""]
    out = ROOT / "docs" / "COVERAGE.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)} ({len(cov)} techniques)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
